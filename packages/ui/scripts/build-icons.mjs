/**
 * Solar has no bare check / close / info / alert glyphs, only circled ones. These are Solar's own
 * glyphs with the outer circle removed and scaled up about the centre; stroke widths and dots are
 * scaled back so they still render at Solar's 1.5px.
 */
const DERIVED = {
  check: { from: 'check-circle', scale: 2 },
  close: { from: 'close-circle', scale: 2.4 },
  info: { from: 'info-circle', scale: 1.6 },
  alert: { from: 'danger-circle', scale: 1.6 },
  add: { from: 'add-circle', scale: 2 },
  minus: { from: 'minus-circle', scale: 2 },
};

const bodyOf = (name) => {
  const icon = solar.icons[`${name}-linear`];
  if (!icon) throw new Error(`Solar has no icon "${name}-linear"`);
  return icon.body;
};

const round = (n) => Number(n.toFixed(4));
function derive({ from, scale }) {
  const inner = bodyOf(from)
    .replace(/<circle cx="12" cy="12" r="10"[^>]*\/>/, '')
    .replace(/stroke-width="1\.5"/g, `stroke-width="${round(1.5 / scale)}"`)
    .replace(/(<circle[^>]*\br=")1(")/g, `$1${round(1 / scale)}$2`);
  if (inner === bodyOf(from)) throw new Error(`Could not strip the circle from ${from}`);
  return `<g transform="translate(12 12) scale(${scale}) translate(-12 -12)">${inner}</g>`;
}

const icons = {
  ...Object.fromEntries(Object.entries(LINEAR).map(([key, name]) => [key, bodyOf(name)])),
  ...Object.fromEntries(Object.entries(DERIVED).map(([key, spec]) => [key, derive(spec)])),
};
const sorted = Object.fromEntries(Object.entries(icons).sort(([a], [b]) => a.localeCompare(b)));

const out = `// Generated by scripts/build-icons.mjs from Solar (Linear) — do not edit by hand.
// Solar icon set by 480 Design, CC BY 4.0: https://icones.js.org/collection/solar
export const icons = ${JSON.stringify(sorted, null, 2)} as const;

export type IconName = keyof typeof icons;
`;
writeFileSync(new URL('../src/components/Icon/icons.generated.ts', import.meta.url), out);
